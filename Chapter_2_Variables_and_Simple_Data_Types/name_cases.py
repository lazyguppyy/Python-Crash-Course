#Objective: Use a variable to represent a person's name, and then print that person's name in lowercase, uppercase, and title case.

first_name = "Leon"
middle_name = "Scott"
last_name = "Kennedy"
full_name = f"{first_name} {middle_name} {last_name}"

print(full_name.title())
print(full_name.upper())
print(full_name.lower())